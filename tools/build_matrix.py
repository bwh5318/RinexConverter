"""Generate docs/CONVERSION_MATRIX.md from tests/expectations/allowed_losses.json.

For every (file type, source version, target version) cell it lists the loss categories
the pre-authorised table allows there. A cell with none is lossless by construction (every
conversion in it must reproduce the data exactly, which the corpus harness checks).

    python tools/build_matrix.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = json.loads((ROOT / "tests" / "expectations" / "allowed_losses.json").read_text(encoding="utf-8"))
READ = ["2.00", "2.01", "2.10", "2.11", "3.00", "3.01", "3.02", "3.03", "3.04", "3.05", "4.00", "4.01", "4.02"]
WRITE = ["2.10", "2.11", "3.00", "3.01", "3.02", "3.03", "3.04", "3.05", "4.00", "4.01", "4.02"]
ALWAYS_POSSIBLE = {"drop-unresolvable", "dedupe"}       # only with an explicit option


def cell(kind, src, tgt):
    cats = []
    for r in TABLE["rules"]:
        if r["kind"] != kind:
            continue
        if "source" in r and not r["source"][0] <= src <= r["source"][1]:
            continue
        if "target" in r and not r["target"][0] <= tgt <= r["target"][1]:
            continue
        w = r.get("when")
        if w in ALWAYS_POSSIBLE:
            continue
        if w in ("source-ne-target", "code-not-in-target") and src == tgt:
            continue
        if w == "lli-bit2-meaning":
            m = lambda v: "AS" if v < "3" else (None if v < "3.01" else "BOC")  # noqa: E731
            if m(src) == m(tgt):
                continue
        if w == "system-not-in-target":
            ss = set(TABLE["systems"].get(src, TABLE["systems"]["2.10"] if src < "2.10" else ""))
            if not ss - set(TABLE["systems"].get(tgt, "")):
                continue
        if w == "label-not-in-target" and src == tgt:
            continue
        cats.append((r["category"].rstrip("*").rstrip(":"), w))
    names = {c for c, w in cats}
    out = set()
    for c, w in cats:
        if w == "with-system-loss" and "system-not-representable" not in names:
            continue
        if w == "with-event-loss" and "event-record-not-representable" not in names:
            continue
        out.add(c)
    return sorted(out)


def main():
    out = ["# Conversion matrix", "",
           "Generated by `tools/build_matrix.py` from `tests/expectations/allowed_losses.json`. "
           "Each cell names the loss categories a conversion may report (the report must then "
           "also give exact counts, and the independent comparator checks them). `—` means "
           "lossless: everything must survive. Losses that need an explicit option "
           "(`--drop-unresolvable`, `--dedupe`) are not shown. Assumptions (attributes, "
           "channels, phase alignment) are separate from losses and listed in each report.", ""]
    for kind in ("obs", "nav", "met"):
        out.append(f"## {kind}")
        out.append("")
        legend = {}
        rows = ["| source \\ target | " + " | ".join(WRITE) + " |",
                "|---" * (len(WRITE) + 1) + "|"]
        for src in READ:
            cells = []
            for tgt in WRITE:
                cats = cell(kind, src, tgt)
                if src == tgt:
                    cells.append("identity" if not cats else "id+" + ",".join(
                        str(legend.setdefault(c, len(legend) + 1)) for c in cats))
                elif not cats:
                    cells.append("—")
                else:
                    cells.append(",".join(str(legend.setdefault(c, len(legend) + 1)) for c in cats))
            rows.append(f"| **{src}** | " + " | ".join(cells) + " |")
        out.extend(rows)
        out.append("")
        out.append("Loss categories:")
        out.append("")
        for c, n in sorted(legend.items(), key=lambda kv: kv[1]):
            cites = [r["cite"] for r in TABLE["rules"] if r["kind"] == kind
                     and r["category"].rstrip("*").rstrip(":") == c]
            out.append(f"{n}. `{c}`: {cites[0] if cites else ''}")
        out.append("")
    (ROOT / "docs" / "CONVERSION_MATRIX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/CONVERSION_MATRIX.md")


if __name__ == "__main__":
    main()
